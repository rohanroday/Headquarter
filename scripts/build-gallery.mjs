// Turns the event photos into web-ready JPEGs + a typed data file.
//
//   node scripts/build-gallery.mjs <folder-of-jpegs>
//
// Input files are named "<Event folder>__<IMG_xxxx>.jpg" (DNG/HEIC are converted to
// JPEG first). Output: public/work/<slug>/<name>.jpg (max 2400px) and
// src/lib/gallery.ts with sizes and tiny blur previews.
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const src = process.argv[2];
if (!src) throw new Error("Usage: node scripts/build-gallery.mjs <folder>");

// Event folder → slug, with the cover photo listed first.
const events = {
  "Chirbirey River Fest": { slug: "chirbirey", cover: "IMG_3108" },
  "Sikkim Utsav": { slug: "sikkim-utsav", cover: "IMG_2061" },
  "Sikkim Kalakar Bharosa Sammelan": { slug: "kalakar-bharosa", cover: "IMG_1484" },
};

const out = {};
for (const file of fs.readdirSync(src).filter((f) => f.endsWith(".jpg")).sort()) {
  const [folder, name] = file.replace(/\.jpg$/, "").split("__");
  const ev = events[folder];
  if (!ev) continue;
  const dir = path.join("public", "work", ev.slug);
  fs.mkdirSync(dir, { recursive: true });
  const dest = path.join(dir, `${name.toLowerCase()}.jpg`);

  const img = sharp(path.join(src, file)).rotate();
  const { data, info } = await img
    .clone()
    .resize(2400, 2400, { fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true, progressive: true })
    .toBuffer({ resolveWithObject: true });
  fs.writeFileSync(dest, data);
  const blur = await img.clone().resize(16, 16, { fit: "inside" }).jpeg({ quality: 50 }).toBuffer();

  (out[ev.slug] ??= []).push({
    src: `/work/${ev.slug}/${name.toLowerCase()}.jpg`,
    width: info.width,
    height: info.height,
    blur: `data:image/jpeg;base64,${blur.toString("base64")}`,
    cover: name === ev.cover,
  });
  console.log(dest, `${info.width}x${info.height}`, `${Math.round(data.length / 1024)}KB`);
}

// Cover first, then the rest in filename order.
for (const list of Object.values(out)) list.sort((a, b) => Number(b.cover) - Number(a.cover));

const body = `// Generated by scripts/build-gallery.mjs — do not edit by hand.
export type Photo = { src: string; width: number; height: number; blur: string; cover: boolean };

export const gallery: Record<string, Photo[]> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(path.join("src", "lib", "gallery.ts"), body);
console.log("wrote src/lib/gallery.ts");
